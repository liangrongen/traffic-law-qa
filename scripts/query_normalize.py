def normalize_query(q: str) -> str:
    """归一化替换，返回归一化文本"""
    out = q
    for pat, repl in REWRITES:
        out = re.sub(pat, repl, out)
    return out


def build_retrieval_text(q: str) -> str:
    """原问题 + 归一化问题双路信息，用于向量检索"""
    q_norm = normalize_query(q)
    if q_norm == q:
        return q
    return f"{q} {q_norm}"